/// Русская плюрализация числительных. До этого хелпера логика
/// дублировалась в `phone_screen.dart`, `sms_code_screen.dart` и
/// нескольких других местах — копи-паст одной и той же mod10/mod100
/// формулы. Любая правка (например, «секунду» → «сек.») требовала
/// синхронных правок по всем файлам.
///
/// Правила русского:
///   - 1, 21, 31, ... 91, 101 — единственное (`секунду`)
///   - 2-4, 22-24, ... — родительный (`секунды`)
///   - 0, 5-20, 25-30, ... — множественное (`секунд`)
///
/// Исключения для 11-14 захардкожены — они идут как множественное,
/// несмотря на окончание цифры.
String pluralRu(int n, String one, String few, String many) {
  final mod10 = n % 10;
  final mod100 = n % 100;
  if (mod100 >= 11 && mod100 <= 14) return many;
  if (mod10 == 1) return one;
  if (mod10 >= 2 && mod10 <= 4) return few;
  return many;
}

/// Готовые формы для «секунда».
String pluralSec(int n) => pluralRu(n, 'секунду', 'секунды', 'секунд');

/// Готовые формы для «минута».
String pluralMin(int n) => pluralRu(n, 'минуту', 'минуты', 'минут');

/// Готовые формы для «отзыв».
String pluralReviews(int n) => pluralRu(n, 'отзыв', 'отзыва', 'отзывов');

/// Готовые формы для «рубль» — для сообщений с числом («1 рубль»,
/// «2 рубля», «5 рублей»). Используется в подсказках про минимальную
/// стоимость заказа и т.п.
String pluralRubles(int n) => pluralRu(n, 'рубль', 'рубля', 'рублей');

/// «$n секунд» / «$n минут» — для retry-таймера. Если ≥ 60 секунд —
/// переводим в минуты с правильной плюрализацией.
String formatRetryAfter(int? retryAfterSec) {
  final s = retryAfterSec ?? 60;
  if (s >= 60) {
    final m = s ~/ 60;
    return '$m ${pluralMin(m)}';
  }
  return '$s ${pluralSec(s)}';
}
