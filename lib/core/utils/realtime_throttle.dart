import 'dart:async';

/// Throttle для realtime-событий с **leading-edge**: ПЕРВОЕ событие
/// выполняет действие сразу (новые статусы/данные появляются в реальном
/// времени), а всплеск последующих в пределах окна [window] склеивается
/// в один догоняющий вызов в конце окна.
///
/// Зачем: подписки на коллекции по `'*'` будят экран на любое чужое
/// событие во всей базе. Без ограничения на росте аудитории это десятки
/// перезапросов в секунду у каждого онлайн-пользователя (нагрузка растёт
/// как O(юзеры²)). Простой trailing-дебаунс это лечит, но ценой задержки
/// КАЖДОГО обновления — а статусы нужны мгновенно. Leading-edge throttle
/// убирает задержку для одиночного события (а это обычный случай) и при
/// этом гасит шторм.
///
/// Поведение под потоком событий: leading сразу → окно → если за окно
/// прилетели ещё события, в конце один догоняющий вызов и новое окно.
/// Итого не чаще одного вызова за [window] при непрерывном потоке, плюс
/// мгновенный самый первый.
class RealtimeThrottle {
  RealtimeThrottle({this.window = const Duration(milliseconds: 800)});

  final Duration window;
  Timer? _timer;
  bool _trailingPending = false;

  /// Зарегистрировать событие. [action] — что сделать (обычно
  /// `ref.invalidate(...)`). Должна быть идемпотентной: догоняющий вызов
  /// просто повторяет её.
  void run(void Function() action) {
    if (_timer != null) {
      // Идёт окно охлаждения — копим один догоняющий вызов в конце.
      _trailingPending = true;
      return;
    }
    action(); // leading edge — мгновенно
    _arm(action);
  }

  void _arm(void Function() action) {
    _timer = Timer(window, () {
      _timer = null;
      if (_trailingPending) {
        _trailingPending = false;
        action(); // догоняющий — учитываем события, пришедшие за окно
        _arm(action); // держим throttle, пока поток не стихнет
      }
    });
  }

  /// Отменить отложенный догоняющий вызов. Вызывать в `dispose()` экрана.
  void dispose() {
    _timer?.cancel();
    _timer = null;
    _trailingPending = false;
  }
}
